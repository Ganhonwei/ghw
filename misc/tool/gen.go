func main() {
	keys := make([]int, 0, len(pb.Commands_name))
	for k := range pb.Commands_name {
		keys = append(keys, int(k))
	}
	sort.Ints(keys)

	for _, key := range keys {
		value := pb.Commands_name[int32(key)]

		if strings.HasSuffix(value, "Req") {
			protosUnpack = append(protosUnpack, proto{name: value, code: key})
		} else if strings.HasSuffix(value, "Rsp") {
			protosPacket = append(protosPacket, proto{name: value, code: key})
		} else if strings.HasSuffix(value, "Ntf") {
			protosPacket = append(protosPacket, proto{name: value, code: key})
		} else {
			fmt.Printf("unknow command %s:%d", value, key)
		}
	}

	var packetStr string
	var unpackStr string
	var rpacketStr string
	var runpackStr string

	packetStr += bodyPacket2(protosPacket)
	unpackStr += bodyUnpack2(protosUnpack)
	rpacketStr += bodyClientPacket2(protosUnpack)
	runpackStr += bodyClientUnpack2(protosPacket)

	//server
	genPacket(packetStr)
	genUnpack(unpackStr)
	//client
	genClientPacket(rpacketStr)
	genClientUnpack(runpackStr)

}
