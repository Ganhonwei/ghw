func genPacket(body string) {
	var str string
	str += headPacket()
	//str += bodyPacket()
	str += body
	str += endPacket()
	err := ioutil.WriteFile(packetPath, []byte(str), 0644)
	if err != nil {
		panic(fmt.Sprintf("write file err -> %v\n", err))
	}
}

