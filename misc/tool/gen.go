func resultPacket(code int) string {
	return fmt.Sprintf("return %d, b, err", code)
}

func resultUnpack() string {
	return fmt.Sprintf(`err := msg.Unmarshal(b)
		return msg, err`)
}

type proto struct {
	name string
	code int
}

var protosPacket = []proto{}
var protosUnpack = []proto{}

