// 计算彩金占比
func GetCashProportion(user *data.User) int32 {
	diamond := user.Diamond
	coin := user.Coin
	if diamond+coin == 0 {
		return 0
	}
	return int32(diamond * 10000 / (diamond + coin))
}

// 生成对局号
func GenGameId(gtype int32) string {
	time := utils.BsonNow().Unix()
	last := utils.RandInt32N(9000) + 1000
	return fmt.Sprintf("%d%d%d", gtype, time, last)
}

func GameFlowWaterLog(value int64, gtype, otype, chargeTimes int, userid string) *pb.GameFlowWaterLog {
	log := &pb.GameFlowWaterLog{
		Gtype:       int32(gtype),
		Outside:     int32(otype),
		Val:         value,
		Userid:      userid,
		ChargeTimes: int32(chargeTimes),
	}
	return log
}

